func TestEveryMachineOperation_RefusesAMachineAvarDoesNotOwn_PROP_6(t *testing.T) {
	// Both halves of ownership: a name that is not avar's at all, and a name
	// that looks like avar's but which avar has no record of. Neither may
	// produce a single subprocess.
	foreign := []string{"default", "colima", "avr-ubuntu-24.04-arm64"}
	records := newFakeRecords() // avar owns nothing

	operations := map[string]func(*Provider, string) error{
		"EnsureMachine": func(p *Provider, name string) error {
			return p.EnsureMachine(context.Background(), provider.MachineSpec{Name: name, Selector: nativeSelector()}, types.DiscardProgress)
		},
		"AppliedMounts": func(p *Provider, name string) error {
			_, err := p.AppliedMounts(context.Background(), name)
			return err
		},
		"SetMounts": func(p *Provider, name string) error {
			return p.SetMounts(context.Background(), name, nil, types.DiscardProgress)
		},
		"Stop": func(p *Provider, name string) error {
			return p.Stop(context.Background(), name, types.DiscardProgress)
		},
		"Delete": func(p *Provider, name string) error {
			return p.Delete(context.Background(), name)
		},
	}

	for op, call := range operations {
		for _, name := range foreign {
			// EnsureMachine and Delete legitimately run before or after a
			// machine has a record, so for them ownership is the name alone.
			nameIsAvars := strings.HasPrefix(name, types.MachineNamePrefix)
			if nameIsAvars && (op == "EnsureMachine" || op == "Delete") {
				continue
			}
			t.Run(op+"/"+name, func(t *testing.T) {
				runner := newFakeRunner().listing(fixture(t, "list-foreign-only.json"))
				p := newTestProvider(t, runner, records)

				err := call(p, name)
				if !errors.Is(err, provider.ErrNotOwned) {
					t.Fatalf("%s(%q) = %v, want an error wrapping ErrNotOwned", op, name, err)
				}
				if calls := runner.calls(); len(calls) != 0 {
					t.Errorf("%s(%q) had side effects before refusing: %v", op, name, runner.argvs())
				}
			})
		}
	}
}

