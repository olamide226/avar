func TestEnsureMachine_ColdCreate_REQ_1_2(t *testing.T) {
	project := t.TempDir()
	runner := newFakeRunner().listing(fixture(t, "list-empty.json"))
	runner.streamOutput = "INFO[0000] Attempting to download the image\nINFO[0042] READY. Run `limactl shell` to open the shell.\n"
	p := newTestProvider(t, runner, newFakeRecords())
	sink := &recordingSink{}

	spec := provider.MachineSpec{
		Name:     testMachine,
		Selector: nativeSelector(),
		Kind:     types.KindShared,
		Mounts:   shares(project),
	}
	if err := p.EnsureMachine(context.Background(), spec, sink); err != nil {
		t.Fatalf("EnsureMachine: %v", err)
	}

	assertArgvs(t, runner.limactlArgvs(), []string{
		"limactl list --json",
		"limactl start --name " + testMachine + " --tty=false " + configPathPlaceholder,
		"limactl shell --workdir / " + testMachine + " -- test -d " + project,
		"limactl shell --workdir / " + testMachine + " -- test -w " + project,
	})

	// The configuration limactl was pointed at is the generated one, not a
	// Lima stock template.
	if !strings.Contains(runner.configWritten, "Generated by avar") {
		t.Errorf("limactl was not given avar's generated configuration:\n%s", runner.configWritten)
	}
	if !strings.Contains(runner.configWritten, `location: "`+project+`"`) {
		t.Errorf("the project directory did not reach the generated configuration:\n%s", runner.configWritten)
	}

	creating := sink.of(types.ProgressCreating)
	if len(creating) != 1 {
		t.Fatalf("want one Creating event, got %d: %v", len(creating), sink.kinds())
	}
	// REQ-1.2 asks for a human-readable line naming the environment and its
	// size, e.g. "Ubuntu 24.04 · arm64 · 4 CPU · 8 GB RAM".
	for _, want := range []string{"Ubuntu 24.04", "CPU", "GB RAM"} {
		if !strings.Contains(creating[0].Message, want) {
			t.Errorf("the Creating message does not mention %q: %q", want, creating[0].Message)
		}
	}
}

