// nativeSelector is an environment that runs without emulation wherever the
// tests happen to run, so that a test about provisioning is not also a test
// about the machine running it.
func nativeSelector() types.EnvironmentSelector {
	return types.EnvironmentSelector{Distro: types.DistroUbuntu, Version: "24.04", Arch: types.HostArch()}
}

// foreignSelector is an environment that must be emulated wherever the tests
// run (REQ-4.6).
func foreignSelector() types.EnvironmentSelector {
	arch := types.ArchAMD64
	if types.HostArch() == types.ArchAMD64 {
		arch = types.ArchARM64
	}
	return types.EnvironmentSelector{Distro: types.DistroUbuntu, Version: "24.04", Arch: arch}
}

const testMachine = "avr-ubuntu-24.04-arm64"

// ownedRecord is avar's record of the machine under test, which is the second
// half of what ownership means (REQ-5.4, PROP-6).
func ownedRecord(name string) types.MachineRecord {
	return types.MachineRecord{Name: name, Provider: types.ProviderLima, Selector: nativeSelector(), Kind: types.KindShared}
}

// shares builds the mount set Lima would be given for these project
// directories: the identity mapping, writable, which is what MapProjectPath
// produces on this backend (REQ-6.1).
func shares(dirs ...string) []types.MountSpec {
	out := make([]types.MountSpec, 0, len(dirs))
	for _, dir := range dirs {
		out = append(out, types.MountSpec{HostPath: dir, GuestPath: dir, Writable: true})
	}
	return out
}

func assertArgvs(t *testing.T, got, want []string) {
	t.Helper()
	if !reflect.DeepEqual(got, want) {
		t.Errorf("limactl was driven differently than expected.\nwant: %v\ngot:  %v", want, got)
	}
}

