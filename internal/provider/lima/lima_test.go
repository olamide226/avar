func TestEnsureMachine_FailedCreateDeletesThePartialMachine_PROP_7(t *testing.T) {
	provisionFailed := errors.New("exit status 1: failed to download the image")
	runner := newFakeRunner().listing(fixture(t, "list-empty.json")).failOn("start", provisionFailed)
	runner.streamOutput = "ERRO[0007] failed to download the image\n"
	p := newTestProvider(t, runner, newFakeRecords())

	err := p.EnsureMachine(context.Background(), provider.MachineSpec{
		Name: testMachine, Selector: nativeSelector(),
	}, types.DiscardProgress)
	if err == nil {
		t.Fatal("a failed provision was reported as success")
	}

	assertArgvs(t, runner.limactlArgvs(), []string{
		"limactl list --json",
		"limactl start --name " + testMachine + " --tty=false " + configPathPlaceholder,
		"limactl delete --force " + testMachine,
	})
	if !errors.Is(err, provisionFailed) {
		t.Errorf("the underlying cause was not wrapped: %v", err)
	}
	// The error has to name the log, because the tail of it is what says why
	// (design §6).
	wantLog := filepath.Join(p.logsDir, testMachine+"-create.log")
	if !strings.Contains(err.Error(), wantLog) {
		t.Errorf("the error does not name the provisioning log %s: %v", wantLog, err)
	}
	if !strings.Contains(err.Error(), "has been removed") {
		t.Errorf("the error does not say the partial machine was cleaned up: %v", err)
	}
}

func TestEnsureMachine_CancellationCleansUpAndWrapsContextError_PROP_7(t *testing.T) {
	// Ctrl-C during provisioning. The cleanup has to happen on a context that
	// is not the cancelled one, or nothing would get cleaned up at all.
	ctx, cancel := context.WithCancel(context.Background())
	runner := newFakeRunner().listing(fixture(t, "list-empty.json"))
	runner.onStream = func(context.Context) error {
		cancel()
		return context.Canceled
	}
	p := newTestProvider(t, runner, newFakeRecords())

	err := p.EnsureMachine(ctx, provider.MachineSpec{
		Name: testMachine, Selector: nativeSelector(),
	}, types.DiscardProgress)
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("an interrupted create must report cancellation, got: %v", err)
	}
	assertArgvs(t, runner.limactlArgvs(), []string{
		"limactl list --json",
		"limactl start --name " + testMachine + " --tty=false " + configPathPlaceholder,
		"limactl delete --force " + testMachine,
	})
	if !strings.Contains(err.Error(), "interrupted") {
		t.Errorf("the error reads like a failure rather than an interruption: %v", err)
	}
}

