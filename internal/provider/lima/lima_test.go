func TestEnsureMachine_WarmPathMakesNoExtraCalls_REQ_17_1(t *testing.T) {
	// The machine in the fixture is Running. This is what happens on every
	// single avr invocation once an environment exists, and the whole latency
	// budget for it is ~500 ms — so it must cost exactly one question to Lima
	// and change nothing.
	runner := newFakeRunner().listing(fixture(t, "list-mixed.json"))
	p := newTestProvider(t, runner, newFakeRecords(ownedRecord("avr-ubuntu-24.04-arm64")))
	sink := &recordingSink{}

	err := p.EnsureMachine(context.Background(), provider.MachineSpec{
		Name:     "avr-ubuntu-24.04-arm64",
		Selector: nativeSelector(),
		// A different mount set than the machine has. EnsureMachine must still
		// not reconfigure: registering a project is SetMounts' job, and doing
		// it here would restart the machine on an ordinary warm invocation.
		Mounts: shares("/Users/dev/code/somewhere-else"),
	}, sink)
	if err != nil {
		t.Fatalf("EnsureMachine: %v", err)
	}

	assertArgvs(t, runner.limactlArgvs(), []string{"limactl list --json"})
	if len(sink.kinds()) != 0 {
		t.Errorf("the warm path emitted progress, which the user would see on every command: %v", sink.kinds())
	}
}

